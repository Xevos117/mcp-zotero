#!/usr/bin/env python3
"""LibreOffice + Zotero's LibreOffice plugin as a second oracle (step "lo-<command>" of run.sh).

Opens the docx in LibreOffice (under Xvfb, with the plugin installed in LO_PROFILE), records what
LibreOffice made of Word's Zotero fields (reference marks, bookmarks, fieldmarks), runs the plugin's
command (refresh, ...) as the Zotero toolbar would, waits for Zotero to finish or ask something, and
saves the result as .docx and .odt. Writes <out>.lo.json. Usage: lo-refresh.py in.docx <out> <command>
Env: LO_PROFILE (LibreOffice user profile dir), ZOTERO_LOG (Zotero's debug log, polled).
"""
import json, os, re, subprocess, sys, threading, time, zipfile

import uno
from com.sun.star.beans import PropertyValue

inp, out, command = sys.argv[1], sys.argv[2], sys.argv[3]
profile, zlog = os.environ["LO_PROFILE"], os.environ["ZOTERO_LOG"]
PORT = 2002
result = {"command": command}


def prop(name, value):
    p = PropertyValue()
    p.Name, p.Value = name, value
    return p


def odt_marks(path):
    xml = zipfile.ZipFile(path).read("content.xml").decode("utf-8")
    return {
        "referenceMarksZotero": len(re.findall(r'<text:reference-mark-start text:name="[^"]*ZOTERO_', xml)),
        "bookmarksZotero": len(re.findall(r'<text:bookmark(?:-start)? text:name="ZOTERO_', xml)),
        "fieldmarks": len(re.findall(r"<field:fieldmark(?:-start)?\b", xml)),
        "fieldmarksZotero": len(re.findall(r"<field:fieldmark(?:-start)?\b[^>]*>(?:(?!</field:fieldmark).)*?ADDIN ZOTERO_", xml, re.S))
        + len(re.findall(r'field:name="[^"]*" field:value="[^"]*ADDIN ZOTERO_', xml)),
        "zoteroTextAnywhere": xml.count("ZOTERO_ITEM"),
    }


def docx_fields(path):
    z = zipfile.ZipFile(path)
    xml = z.read("word/document.xml").decode("utf-8")
    custom = z.read("docProps/custom.xml").decode("utf-8") if "docProps/custom.xml" in z.namelist() else ""
    instr = "".join(re.findall(r"<w:instrText[^>]*>([^<]*)</w:instrText>", xml))
    return {
        "fieldsBegin": xml.count('w:fldCharType="begin"'),
        "zoteroItemCodes": instr.count("ADDIN ZOTERO_ITEM"),
        "zoteroBiblCodes": instr.count("ADDIN ZOTERO_BIBL"),
        "bookmarksZotero": len(re.findall(r'<w:bookmarkStart[^>]*w:name="ZOTERO_', xml)),
        "zoteroPrefs": "ZOTERO_PREF_1" in custom,
        "placeholderLeft": "[Bibliography will be generated by Zotero]" in xml,
    }


def zotero_since(offset):
    with open(zlog, encoding="utf-8", errors="replace") as f:
        f.seek(offset)
        text = f.read()
    alerts = re.findall(r'LibreOfficePlugin: Sending \d+ \["Document_displayAlert",\[\d+,"((?:[^"\\]|\\.)*)"', text)
    m = re.findall(r'LibreOfficePlugin: Read \d+ \[\[([\d,]*)\],', text)
    return {
        "invoked": f"LibreOffice-{command} invoked" in text,
        "completed": '"Document_complete"' in text,
        "docPrefsDialog": "integrationDocPrefs" in text,
        "alerts": [a[:200] for a in alerts],
        "fieldsSeenByZotero": max((len([x for x in g.split(",") if x]) for g in m), default=0),
        "error": next(iter(re.findall(r"Integration: (?:Error|error)[^\n]{0,160}", text)), None),
    }


def store(doc, path, filt):
    done = threading.Event()

    def run():
        try:
            doc.storeToURL(uno.systemPathToFileUrl(path), (prop("FilterName", filt), prop("Overwrite", True)))
        finally:
            done.set()

    threading.Thread(target=run, daemon=True).start()
    return done.wait(30)


soffice = subprocess.Popen(
    ["soffice", f"-env:UserInstallation=file://{profile}", "--norestore", "--nologo", "--nodefault",
     "--nolockcheck", f"--accept=socket,host=127.0.0.1,port={PORT};urp;"],
    stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
)
try:
    local = uno.getComponentContext()
    resolver = local.ServiceManager.createInstanceWithContext("com.sun.star.bridge.UnoUrlResolver", local)
    ctx = None
    for _ in range(90):
        try:
            ctx = resolver.resolve(f"uno:socket,host=127.0.0.1,port={PORT};urp;StarOffice.ComponentContext")
            break
        except Exception:
            time.sleep(1)
    if ctx is None:
        raise RuntimeError("LibreOffice did not start")
    smgr = ctx.ServiceManager
    cp = smgr.createInstanceWithContext("com.sun.star.configuration.ConfigurationProvider", ctx)
    about = cp.createInstanceWithArguments("com.sun.star.configuration.ConfigurationAccess",
                                           (prop("nodepath", "/org.openoffice.Setup/Product"),))
    result["libreoffice"] = f"{about.getByName('ooName')} {about.getByName('ooSetupVersionAboutBox')}"
    desktop = smgr.createInstanceWithContext("com.sun.star.frame.Desktop", ctx)
    doc = desktop.loadComponentFromURL(uno.systemPathToFileUrl(os.path.abspath(inp)), "_blank", 0, ())
    result["opened"] = {
        "referenceMarks": len(doc.getReferenceMarks().getElementNames()),
        "referenceMarksZotero": len([n for n in doc.getReferenceMarks().getElementNames() if "ZOTERO_" in n]),
        "bookmarksZotero": len([n for n in doc.getBookmarks().getElementNames() if n.startswith("ZOTERO_")]),
    }
    if store(doc, out + ".before.odt", "writer8"):
        result["opened"].update(odt_marks(out + ".before.odt"))

    if command == "none":  # import/export only, no Zotero command
        saved = store(doc, out + ".docx", "MS Word 2007 XML")
        result["saved"] = saved
        if saved:
            result["afterDocx"] = docx_fields(out + ".docx")
        raise SystemExit
    offset = os.path.getsize(zlog)
    dispatcher = smgr.createInstanceWithContext("com.sun.star.frame.DispatchHelper", ctx)
    frame = doc.getCurrentController().getFrame()
    t0 = time.time()
    threading.Thread(target=lambda: dispatcher.executeDispatch(
        frame, f"service:org.zotero.integration.ooo.ZoteroOpenOfficeIntegration?{command}", "", 0, ()),
        daemon=True).start()
    while time.time() - t0 < 60:
        z = zotero_since(offset)
        if z["completed"] or z["alerts"]:
            break
        time.sleep(1)
    time.sleep(2)
    result["zotero"] = zotero_since(offset)
    result["zotero"]["seconds"] = round(time.time() - t0, 1)
    saved = store(doc, out + ".docx", "MS Word 2007 XML") and store(doc, out + ".odt", "writer8")
    result["saved"] = saved
    if saved:
        result["afterDocx"] = docx_fields(out + ".docx")
        result["afterOdt"] = odt_marks(out + ".odt")
    else:
        result["saved"] = "blocked (a dialog is open in LibreOffice)"
except SystemExit:
    pass
except Exception as e:  # report, never hang
    result["exception"] = f"{type(e).__name__}: {e}"[:300]
finally:
    soffice.kill()
    soffice.wait(10)
    with open(out + ".lo.json", "w") as f:
        json.dump(result, f, indent=1)
    print(json.dumps({k: result.get(k) for k in ("libreoffice", "opened", "zotero", "saved", "exception")}))
