// Reads a run directory (refreshed docx + Zotero debug log + wordcraft traces) and reports the
// Word-checklist hypotheses as JSON (stdout) and a Markdown table ($GITHUB_STEP_SUMMARY when set).
// Exit 1 only when a Zotero command did not complete (infrastructure), never on a hypothesis verdict.
// Usage: node verify.mjs <rundir> <label>...
import { readFile, appendFile } from "node:fs/promises";
import { join } from "node:path";
import JSZip from "jszip";

const [dir, ...names] = process.argv.slice(2);
const log = await readFile(join(dir, "zotero.log"), "utf8");
const wc = log.split("\n").filter((l) => l.startsWith("WCAUTO ")).map((l) => JSON.parse(l.slice(7)));
const dec = (s) => s.replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");

function fields(xml) {
  // Concatenate instrText per field (Zotero may split long codes over several runs)
  const out = [];
  let cur = null;
  for (const m of xml.matchAll(/<w:fldChar w:fldCharType="(begin|separate|end)"\/>|<w:instrText[^>]*>([\s\S]*?)<\/w:instrText>/g)) {
    if (m[1] === "begin") cur = "";
    else if (m[1] === "separate" || m[1] === "end") { if (cur !== null) out.push(dec(cur)); cur = null; }
    else if (cur !== null) cur += m[2];
  }
  return out.map((c) => c.trim());
}

const report = { zotero: wc.find((e) => e.ready)?.zotero, docs: {} };
for (const name of names) {
  const trace = await readFile(join(dir, `${name}.trace`), "utf8").catch(() => "");
  const zip = await JSZip.loadAsync(await readFile(join(dir, `${name}.refreshed.docx`)));
  const xml = await zip.file("word/document.xml").async("string");
  const custom = (await zip.file("docProps/custom.xml")?.async("string")) ?? "";
  const codes = fields(xml);
  const cites = codes.filter((c) => c.startsWith("ADDIN ZOTERO_ITEM CSL_CITATION ")).map((c) => JSON.parse(c.slice("ADDIN ZOTERO_ITEM CSL_CITATION ".length)));
  const bibl = codes.filter((c) => c.startsWith("ADDIN ZOTERO_BIBL"));
  const text = [...xml.matchAll(/<w:t[^>]*>([^<]*)<\/w:t>/g)].map((m) => dec(m[1])).join("");
  const bibParas = [...xml.matchAll(/<w:p>(?:(?!<\/w:p>)[\s\S])*?w:val="Bibliography"[\s\S]*?<\/w:p>/g)].length;
  // Each refresh call is one Zotero command: the n-th docx's dialogs are the n-th group in the log
  const start = wc.findIndex((e) => e.step === name);
  const end = wc.findIndex((e, i) => i > start && e.step);
  const seg = start < 0 ? [] : wc.slice(start + 1, end < 0 ? undefined : end);
  const footnotes = (await zip.file("word/footnotes.xml")?.async("string")) ?? "";
  const uris = cites.flatMap((c) => c.citationItems.map((i) => i.uris[0]));
  const idsByUri = {};
  for (const c of cites) for (const i of c.citationItems) (idsByUri[i.uris[0]] ??= new Set()).add(String(i.id));
  report.docs[name] = {
    completed: /calls, completed/.test(trace),
    H1_docPrefsDialog: seg.some((e) => /integrationDocPrefs/.test(e.dialog ?? "")),
    docPrefsAnswer: seg.find((e) => e.answer)?.answer,
    otherDialogs: seg.filter((e) => e.dialog && !/integrationDocPrefs/.test(e.dialog)).map((e) => e.dialog),
    footnoteCitations: (footnotes.match(/ZOTERO_ITEM/g) ?? []).length,
    alerts: (trace.match(/← Document_displayAlert[^\n]*/g) ?? []).map((s) => s.slice(0, 200)),
    citations: cites.length,
    visible: cites.map((c) => c.properties.formattedCitation),
    H1_prefsWritten: /ZOTERO_PREF_1/.test(custom),
    H1_styleInDoc: dec(custom).match(/style id="([^"]+)"/)?.[1],
    H2_noteIndex: cites.map((c) => c.properties.noteIndex),
    H2_plainCitation: cites.map((c) => "plainCitation" in c.properties),
    H3_idsPerUri: Object.fromEntries(Object.entries(idsByUri).map(([u, s]) => [u.split("/").pop(), [...s]])),
    H3_distinctUris: new Set(uris).size,
    H4_locatorRendered: cites.filter((c) => c.citationItems.some((i) => i.locator)).map((c) => c.properties.formattedCitation),
    bibliographyFields: bibl.length,
    bibliographyParagraphs: bibParas,
    bibliographyPlaceholderLeft: text.includes("[Bibliography will be generated by Zotero]"),
  };
}
report.proposedStyles = [...new Set(wc.filter((e) => e.proposedStyle).map((e) => e.proposedStyle))];
report.H5_embeddedFallback = [...new Set([...log.matchAll(/Item \["([^"]+)"\] not in library\. Using embedded data/g)].map((m) => m[1].split("/").pop()))];
report.missingItemPrompts = (log.match(/missingItem/g) ?? []).length;
report.libraryLoaded = wc.filter((e) => e.loaded !== undefined).map((e) => ({ library: e.library, items: e.loaded }));
if (!report.libraryLoaded.length) report.libraryLoaded = undefined;
report.setupErrors = wc.filter((e) => e.setupError).map((e) => e.setupError);
const d = report.docs;
const injected = names.filter((n) => !n.startsWith("fix") && !["again", "restyle"].includes(n) && n !== "proposed");
const all = Object.values(d);
report.verdicts = {
  H1: injected.every((n) => d[n].H1_docPrefsDialog) ? "confermata: il primo Refresh chiede Document Preferences" : "smentita",
  H1_fix: !names.some((n) => n.startsWith("fix")) ? "non provato" : names.filter((n) => n.startsWith("fix")).every((n) => !d[n].H1_docPrefsDialog) ? "con ZOTERO_PREF_1 nel docx nessun dialogo" : "il fix non basta",
  H2: all.every((x) => x.alerts.length === 0 && x.H2_noteIndex.every((i) => i === 0)) ? "smentita: nessun avviso, noteIndex 0 scritto da Zotero" : "da rivedere",
  H3: all.every((x) => Object.values(x.H3_idsPerUri).every((ids) => ids.length === 1) && x.bibliographyParagraphs === x.H3_distinctUris) ? "smentita: un id per URI, bibliografia senza duplicati" : "da rivedere",
  H4: all.every((x) => x.H4_locatorRendered.every((t) => /\bp\. 12\b|\b12\b/.test(t))) ? "smentita: locator reso come pagina" : "da rivedere",
  H5: report.missingItemPrompts !== 0 ? "da rivedere: Zotero ha chiesto delle voci mancanti"
    : report.libraryLoaded ? (report.H5_embeddedFallback.length === 0 ? "tutte le voci risolte dalla libreria locale (URI utente e gruppo)" : `voci non risolte dalla libreria: ${report.H5_embeddedFallback.join(", ")}`)
    : report.H5_embeddedFallback.length > 0 ? "itemData incorporato usato senza richieste (voci non in libreria)" : "da rivedere",
};
console.log(JSON.stringify(report, null, 2));
if (process.env.GITHUB_STEP_SUMMARY) {
  const rows = names.map((n) => `| ${n} | ${d[n].completed ? "ok" : "**non completato**"} | ${d[n].H1_docPrefsDialog ? "sì" : "no"} | ${d[n].H1_styleInDoc ?? ""} | ${d[n].alerts.length} | ${d[n].visible.join(" · ").replace(/\|/g, "/")} | ${d[n].bibliographyParagraphs} |`);
  await appendFile(process.env.GITHUB_STEP_SUMMARY, [`### Zotero ${report.zotero} + WordCraft`, "", "| passo | comando | Document Preferences | stile salvato | avvisi | citazioni | voci bibliografia |", "|---|---|---|---|---|---|---|", ...rows, "", ...Object.entries(report.verdicts).map(([k, v]) => `- **${k}**: ${v}`), ""].join("\n"));
}
if (!all.every((x) => x.completed) || report.setupErrors.length) process.exitCode = 1;
