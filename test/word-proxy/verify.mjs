// Reads one word-proxy session directory (refreshed docx, wordcraft traces, events.jsonl written by run.sh) and
// reports, per step, what Zotero did with the injected document: dialogs, alerts, field properties, item ids,
// bibliography, embedded-data fallbacks. JSON on stdout, a Markdown table in $GITHUB_STEP_SUMMARY when set.
// With --expect <expect.json> every step's expectations are checked and the exit code is 1 on any mismatch;
// without it, exit 1 only when a command did not complete. Every session also fails on a setup error, a prompt for
// a missing item, or a load-items.js run that did not load the whole corpus.
// Usage: node verify.mjs <sessiondir> [--expect expect.json] <step>...
import { readFile, appendFile } from "node:fs/promises";
import { join } from "node:path";
import JSZip from "jszip";

const DOC_PREFS = /integrationDocPrefs/;
const dec = (s) => s.replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");

/** Field codes of document.xml, instrText concatenated per field (Zotero may split long codes over several runs). */
export function fieldCodes(xml) {
  const out = [];
  let cur = null;
  for (const m of xml.matchAll(/<w:fldChar w:fldCharType="(begin|separate|end)"\/>|<w:instrText[^>]*>([\s\S]*?)<\/w:instrText>/g)) {
    if (m[1] === "begin") cur = "";
    else if (m[1] === "separate" || m[1] === "end") {
      if (cur !== null) out.push(dec(cur).trim());
      cur = null;
    } else if (cur !== null) cur += m[2];
  }
  return out;
}

const paragraphText = (p) => [...p.matchAll(/<w:t[^>]*>([^<]*)<\/w:t>/g)].map((m) => dec(m[1])).join("");

/** Facts of one refreshed document. `events`: the plugin/log events of its step. */
export async function inspect(docx, trace, events) {
  const zip = await JSZip.loadAsync(docx);
  const xml = await zip.file("word/document.xml").async("string");
  const custom = (await zip.file("docProps/custom.xml")?.async("string")) ?? "";
  const footnotes = (await zip.file("word/footnotes.xml")?.async("string")) ?? "";
  const codes = fieldCodes(xml);
  const PREFIX = "ADDIN ZOTERO_ITEM CSL_CITATION ";
  const cites = codes.filter((c) => c.startsWith(PREFIX)).map((c) => JSON.parse(c.slice(PREFIX.length)));
  const paragraphs = [...xml.matchAll(/<w:p[ >][\s\S]*?<\/w:p>/g)].map((m) => m[0]);
  const bibliography = paragraphs.filter((p) => /w:val="Bibliography"/.test(p)).map(paragraphText);
  // visible text of the body (citations as Zotero rendered them), without the bibliography
  const text = paragraphs.filter((p) => !/w:val="Bibliography"/.test(p)).map(paragraphText);
  const idsByUri = {};
  for (const c of cites) for (const i of c.citationItems) (idsByUri[i.uris[0]] ??= new Set()).add(String(i.id));
  const dialogs = events.filter((e) => e.dialog);
  const docPrefs = dialogs.find((e) => DOC_PREFS.test(e.dialog));
  return {
    completed: /calls, completed/.test(trace),
    docPrefsDialog: Boolean(docPrefs),
    proposedStyle: docPrefs?.proposedStyle,
    docPrefsAnswer: events.find((e) => e.answer)?.answer,
    otherDialogs: dialogs.filter((e) => !DOC_PREFS.test(e.dialog)).map((e) => e.dialog),
    alerts: (trace.match(/← Document_displayAlert[^\n]*/g) ?? []).map((s) => s.slice(0, 200)),
    citations: cites.length,
    visible: cites.map((c) => c.properties.formattedCitation ?? ""),
    text,
    noteIndex: [...new Set(cites.map((c) => c.properties.noteIndex))],
    oneIdPerUri: Object.values(idsByUri).every((ids) => ids.size === 1),
    distinctUris: Object.keys(idsByUri).length,
    uris: Object.keys(idsByUri).sort(),
    footnoteCitations: (footnotes.match(/ZOTERO_ITEM/g) ?? []).length,
    bibliographyFields: codes.filter((c) => c.startsWith("ADDIN ZOTERO_BIBL")).length,
    bibliography,
    bibliographyEntries: bibliography.length,
    placeholderLeft: paragraphs.some((p) => paragraphText(p).includes("[Bibliography will be generated by Zotero]")),
    prefsWritten: /ZOTERO_PREF_1/.test(custom),
    styleInDoc: dec(dec(custom)).match(/style id="([^"]+)"/)?.[1],
    embeddedFallback: [...new Set(events.filter((e) => e.embedded).map((e) => e.embedded.split("/").pop()))].sort(),
  };
}

/** Mismatches between a step's facts and its expectations (empty = as expected). */
export function check(facts, exp) {
  const out = [];
  const eq = (name, got, want) => {
    if (JSON.stringify(got) !== JSON.stringify(want)) out.push(`${name}: expected ${JSON.stringify(want)}, got ${JSON.stringify(got)}`);
  };
  if (!facts.completed) out.push("command did not complete");
  for (const [k, want] of Object.entries(exp)) {
    switch (k) {
      case "knownBug":
      case "why":
        break;
      case "alerts":
        eq(k, facts.alerts.length, want);
        break;
      case "otherDialogs":
        eq(k, facts.otherDialogs.length, want);
        break;
      case "noteIndex":
        eq(k, facts.noteIndex, [want]);
        break;
      case "embeddedFallback":
        if (want === "all") eq(k, facts.embeddedFallback, facts.uris.map((u) => u.split("/").pop()).sort());
        else eq(k, facts.embeddedFallback, [...want].sort());
        break;
      case "visibleIncludes":
      case "bibliographyIncludes":
      case "visibleExcludes":
      case "bibliographyExcludes": {
        const text = (k.startsWith("visible") ? facts.text : facts.bibliography).join("\n");
        for (const s of want) {
          const has = text.includes(s);
          if (k.endsWith("Includes") && !has) out.push(`${k}: "${s}" missing`);
          if (k.endsWith("Excludes") && has) out.push(`${k}: "${s}" present`);
        }
        break;
      }
      case "uriPrefix":
        if (!facts.uris.length || !facts.uris.every((u) => u.startsWith(want))) out.push(`uriPrefix: expected ${want}, got ${facts.uris.join(", ")}`);
        break;
      default:
        if (!(k in facts)) out.push(`unknown expectation ${k}`);
        else eq(k, facts[k], want);
    }
  }
  return out;
}

async function main(argv) {
  const ei = argv.indexOf("--expect");
  const expect = ei >= 0 ? JSON.parse(await readFile(argv[ei + 1], "utf8")) : null;
  const [dir, ...steps] = argv.filter((_, i) => ei < 0 || (i !== ei && i !== ei + 1));
  const events = (await readFile(join(dir, "events.jsonl"), "utf8"))
    .split("\n")
    .filter(Boolean)
    .map((l) => JSON.parse(l));
  const library = JSON.parse(await readFile(new URL("../fixtures/corpus/library.json", import.meta.url), "utf8"));
  const report = { zotero: events.find((e) => e.ready)?.zotero, steps: {}, problems: {} };
  for (const step of steps) {
    const start = events.findIndex((e) => e.step === step);
    const end = events.findIndex((e, i) => i > start && e.step);
    const seg = start < 0 ? [] : events.slice(start + 1, end < 0 ? undefined : end);
    const trace = await readFile(join(dir, `${step}.trace`), "utf8").catch(() => "");
    const docx = await readFile(join(dir, `${step}.refreshed.docx`)).catch(() => null);
    const facts = docx ? await inspect(docx, trace, seg) : { completed: false };
    report.steps[step] = facts;
    // "_all": expectations of every step, overridden by the step's own
    const exp = expect ? expect[step] && { ...expect._all, ...expect[step] } : {};
    if (expect && !exp) report.problems[step] = [`no expectations for step ${step} in expect.json`];
    else {
      const p = docx ? check(facts, exp) : ["no refreshed document"];
      if (expect ? p.length : !facts.completed) report.problems[step] = p;
    }
  }
  const session = [];
  for (const e of events.filter((x) => x.setupError)) session.push(`setup error: ${e.setupError}`);
  if (events.some((e) => e.missingItem)) session.push("Zotero asked for a missing item");
  for (const e of events.filter((x) => x.loaded !== undefined)) {
    if (e.loaded !== library.items.length) session.push(`load-items: ${e.loaded} items in the ${e.library} library, expected ${library.items.length}`);
  }
  if (session.length) report.problems.session = session;
  console.log(JSON.stringify(report, null, 2));
  if (process.env.GITHUB_STEP_SUMMARY) await appendFile(process.env.GITHUB_STEP_SUMMARY, summary(dir, report, expect));
  if (Object.keys(report.problems).length) {
    for (const [step, p] of Object.entries(report.problems)) for (const m of p) console.error(`word-proxy ${step}: ${m}`);
    process.exitCode = 1;
  }
}

function summary(dir, report, expect) {
  const cell = (s) => String(s ?? "").replace(/\|/g, "/").replace(/\n/g, " ");
  const rows = Object.entries(report.steps).map(([step, d]) => {
    const bug = expect?.[step]?.knownBug ? ` (bug noto ${expect[step].knownBug})` : "";
    const verdict = report.problems[step] ? `**${report.problems[step].length} differenze**` : "ok";
    return `| ${step} | ${verdict} | ${d.docPrefsDialog ? `sì${bug}` : "no"} | ${cell(d.styleInDoc)} | ${d.alerts?.length ?? ""} | ${cell(d.text?.slice(1, 4).join(" · "))} | ${d.bibliographyEntries ?? ""} | ${d.embeddedFallback?.length ?? ""} |`;
  });
  const problems = Object.entries(report.problems).flatMap(([s, p]) => p.map((m) => `- \`${s}\`: ${cell(m)}`));
  return [
    `### word-proxy: Zotero ${report.zotero ?? "?"} + WordCraft (${dir.split("/").pop()})`,
    "",
    "| passo | esito | Document Preferences | stile nel documento | avvisi | prime citazioni | voci bibliografia | voci da itemData |",
    "|---|---|---|---|---|---|---|---|",
    ...rows,
    "",
    ...(problems.length ? ["Differenze dalle aspettative (`test/word-proxy/expect.json`):", "", ...problems, ""] : []),
  ].join("\n");
}

if (process.argv[1] && process.argv[1].endsWith("verify.mjs")) await main(process.argv.slice(2));
