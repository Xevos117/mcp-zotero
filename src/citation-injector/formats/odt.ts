import JSZip from "jszip";
import { randomBytes } from "node:crypto";
import { FormatWriter } from "./types.js";
import { InjectionError, PreparedCitation } from "../model.js";
import { escapeXml } from "../xml-utils.js";
import { buildCslCitation } from "../citation-json.js";
import { normalizeOdtZciteTags, normalizeOdtPandocMarkers } from "../odt-normalizer.js";
import { DocumentPrefsOutcome, ZOTERO_STYLE_IDS, prefChunks, zoteroDocumentData } from "../document-prefs.js";

/**
 * Scrittore LibreOffice (ODT): le citazioni sono reference mark, la bibliografia una text:section, le
 * preferenze vanno in meta.xml con fieldType ReferenceMark. Condivide con Word tutto il nucleo neutro
 * (parsing <zcite>, JSON CSL della citazione, risoluzione delle chiavi); qui vive solo ciò che è ODF.
 */

const ODT_MIME = "application/vnd.oasis.opendocument.text";
const REGENERATE_ODT =
  "The file is not a LibreOffice document or is corrupted: create it again as .odt and call again.";

/** 10 caratteri [0-9A-Za-z], il suffisso RND che Zotero accoda ai nomi dei reference mark. */
const RND_ALPHABET = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz";
function rnd10(): string {
  return [...randomBytes(10)].map((b) => RND_ALPHABET[b % RND_ALPHABET.length]).join("");
}

/** Reference mark di una citazione: start/end con lo stesso nome ZOTERO_ITEM CSL_CITATION {json} RND…, testo in mezzo. */
function citationXml(prepared: PreparedCitation): string {
  const csl = buildCslCitation(prepared.items, prepared.formattedText);
  const name = escapeXml(`ZOTERO_ITEM CSL_CITATION ${JSON.stringify(csl)} RND${rnd10()}`);
  return (
    `<text:reference-mark-start text:name="${name}"/>` +
    escapeXml(prepared.formattedText) +
    `<text:reference-mark-end text:name="${name}"/>`
  );
}

/** Sezione ZOTERO_BIBL seguita da un paragrafo vuoto, prima di </office:text>. */
function appendBibliography(contentXml: string): string {
  const name = escapeXml(`ZOTERO_BIBL {"uncited":[],"omitted":[],"custom":[]} CSL_BIBLIOGRAPHY RND${rnd10()}`);
  const section =
    `<text:section text:name="${name}">` +
    `<text:p text:style-name="Bibliography_20_1">[Bibliography will be generated by Zotero]</text:p>` +
    `</text:section><text:p/>`;
  return contentXml.replace("</office:text>", `${section}</office:text>`);
}

const BIBLIOGRAPHY_STYLE =
  '<style:style style:name="Bibliography_20_1" style:display-name="Bibliography 1" style:family="paragraph" style:parent-style-name="Standard" style:class="list"/>';

/** Definisce lo stile Bibliography_20_1 in styles.xml se manca (dentro office:styles, o creando il blocco). */
async function ensureBibliographyStyle(zip: JSZip): Promise<void> {
  const entry = zip.file("styles.xml");
  if (!entry) return;
  let styles = await entry.async("string");
  if (styles.includes('style:name="Bibliography_20_1"')) return;
  if (styles.includes("</office:styles>")) {
    styles = styles.replace("</office:styles>", `${BIBLIOGRAPHY_STYLE}</office:styles>`);
  } else if (/<office:styles\s*\/>/.test(styles)) {
    styles = styles.replace(/<office:styles\s*\/>/, `<office:styles>${BIBLIOGRAPHY_STYLE}</office:styles>`);
  } else {
    return; // nessun posto riconoscibile: lo stile non è definito, LibreOffice userà Standard
  }
  zip.file("styles.xml", styles);
}

export const EXISTING_ODT_PREFS_WARNING =
  "The document already has Zotero document preferences (ZOTERO_PREF_* in meta.xml): kept as they are, so on the " +
  "first Refresh Zotero uses the style saved there, not the style of this injection.";
export const ODT_PREFS_NOT_WRITTEN_WARNING =
  "Zotero document preferences not written: meta.xml has no <office:meta> to merge into, so Zotero may ask for the " +
  "document style (Document Preferences) on the first Refresh.";

/** Preferenze in meta.xml: meta:user-defined ZOTERO_PREF_1…n (255 caratteri), fieldType ReferenceMark. */
async function writeOdtPrefs(zip: JSZip, style: string): Promise<DocumentPrefsOutcome> {
  const styleId = ZOTERO_STYLE_IDS[style];
  if (!styleId) return "skipped";
  const entry = zip.file("meta.xml");
  const meta = entry ? await entry.async("string") : undefined;
  if (meta === undefined) return "skipped";
  if (/\bmeta:name=["']ZOTERO_PREF_\d+["']/.test(meta)) return "kept";
  const value = zoteroDocumentData(styleId, "ReferenceMark");
  const props = prefChunks(value)
    .map((chunk, i) => `<meta:user-defined meta:name="ZOTERO_PREF_${i + 1}">${escapeXml(chunk)}</meta:user-defined>`)
    .join("");
  const close = "</office:meta>";
  const at = meta.lastIndexOf(close);
  if (at < 0) {
    // office:meta vuoto <office:meta/>
    const m = /<office:meta\b([^>]*)\/>/.exec(meta);
    if (!m) return "skipped";
    zip.file("meta.xml", meta.replace(m[0], `<office:meta${m[1]}>${props}</office:meta>`));
    return "written";
  }
  zip.file("meta.xml", meta.slice(0, at) + props + meta.slice(at));
  return "written";
}

export const odtWriter: FormatWriter = {
  format: "odt",
  fieldType: "ReferenceMark",
  bodyPart: "content.xml",
  app: "LibreOffice",
  invalidPackageMessage: (detail) => `Invalid .odt file: not a readable ZIP archive (${detail}). ${REGENERATE_ODT}`,
  bodyMissingMessage: `Invalid .odt file: content.xml not found. ${REGENERATE_ODT}`,
  sniff(zip: JSZip) {
    // un .docx passato come .odt (o viceversa): meglio un errore chiaro di un "content.xml not found"
    if (zip.file("word/document.xml")) {
      throw new InjectionError("format_mismatch", "This looks like a Word .docx, not a LibreOffice .odt. Use format \"docx\" (or a .docx file).");
    }
  },
  normalize: (bodyXml) => normalizeOdtZciteTags(bodyXml),
  normalizePandoc: (bodyXml) => normalizeOdtPandocMarkers(bodyXml),
  citationXml,
  replaceTag: (bodyXml, rawTag, cite) => {
    const at = bodyXml.indexOf(rawTag);
    return at < 0 ? bodyXml : bodyXml.slice(0, at) + cite + bodyXml.slice(at + rawTag.length);
  },
  appendBibliography,
  writePrefs: writeOdtPrefs,
  prefsWarnings: (outcome: DocumentPrefsOutcome) => {
    if (outcome === "kept") return [EXISTING_ODT_PREFS_WARNING];
    if (outcome === "skipped") return [ODT_PREFS_NOT_WRITTEN_WARNING];
    return [];
  },
  async finalize(zip: JSZip) {
    await ensureBibliographyStyle(zip);
    // mimetype deve restare STORED (non compresso): lo riscrivo con STORE, mantenendo la posizione
    const mimetype = zip.file("mimetype");
    if (mimetype) zip.file("mimetype", await mimetype.async("uint8array"), { compression: "STORE" });
  },
  generateOptions: { compression: "DEFLATE" },
  async skeleton() {
    const NS =
      'xmlns:office="urn:oasis:names:tc:opendocument:xmlns:office:1.0" xmlns:text="urn:oasis:names:tc:opendocument:xmlns:text:1.0" ' +
      'xmlns:style="urn:oasis:names:tc:opendocument:xmlns:style:1.0" xmlns:fo="urn:oasis:names:tc:opendocument:xmlns:xsl-fo-compatible:1.0" ' +
      'xmlns:meta="urn:oasis:names:tc:opendocument:xmlns:meta:1.0"';
    const zip = new JSZip();
    zip.file("mimetype", ODT_MIME, { compression: "STORE" });
    zip.file(
      "META-INF/manifest.xml",
      '<?xml version="1.0" encoding="UTF-8"?><manifest:manifest xmlns:manifest="urn:oasis:names:tc:opendocument:xmlns:manifest:1.0" manifest:version="1.3">' +
        `<manifest:file-entry manifest:full-path="/" manifest:version="1.3" manifest:media-type="${ODT_MIME}"/>` +
        '<manifest:file-entry manifest:full-path="content.xml" manifest:media-type="text/xml"/>' +
        '<manifest:file-entry manifest:full-path="styles.xml" manifest:media-type="text/xml"/>' +
        '<manifest:file-entry manifest:full-path="meta.xml" manifest:media-type="text/xml"/></manifest:manifest>'
    );
    zip.file(
      "content.xml",
      `<?xml version="1.0" encoding="UTF-8"?><office:document-content ${NS}>` +
        '<office:automatic-styles>' +
        '<style:style style:name="T_Bold" style:family="text"><style:text-properties fo:font-weight="bold"/></style:style>' +
        '<style:style style:name="T_Italic" style:family="text"><style:text-properties fo:font-style="italic"/></style:style>' +
        '</office:automatic-styles><office:body><office:text></office:text></office:body></office:document-content>'
    );
    const headingSizes = ["18pt", "16pt", "14pt", "13pt", "12pt", "11pt"];
    const headings = headingSizes
      .map(
        (sz, i) =>
          `<style:style style:name="Heading_20_${i + 1}" style:display-name="Heading ${i + 1}" style:family="paragraph" style:default-outline-level="${i + 1}" style:class="text"><style:text-properties fo:font-weight="bold" fo:font-size="${sz}"/></style:style>`
      )
      .join("");
    zip.file("styles.xml", `<?xml version="1.0" encoding="UTF-8"?><office:document-styles ${NS}><office:styles>${headings}</office:styles></office:document-styles>`);
    zip.file("meta.xml", `<?xml version="1.0" encoding="UTF-8"?><office:document-meta ${NS}><office:meta/></office:document-meta>`);
    return zip;
  },
};
